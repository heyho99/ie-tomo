import type { ToolDef } from './index.js';

/** 共有している画面を見る。画面の1コマはブラウザからもらう（ctx.screen） */
export const lookAtScreen: ToolDef = {
  name: 'look_at_screen',
  label: '共有している画面を見る',
  description: '生徒が共有している画面（別タブで見ている教材など）を見る。勉強の様子に「画面共有：オン」とあるときに使える。生徒が画面に映っているものについて話したとき（「この画面見て」「この図は？」「ここがわからない」など）に呼び、推測で答えずに見てから答える。呼ぶと、いまの画面の画像が届く。画像に重なった手書きの線・丸・四角・矢印・マーカーは、生徒がペンで書き込んだもの（聞きたい所の印や、生徒が書いた文字・図）',
  features: [{ name: '画面を見る', hint: '「この画面見て」「ここがわからない」' }],
  async run(ctx) {
    const image = await ctx.screen();
    return image
      ? { result: { result: '生徒が共有している、いまの画面の画像です。手書きの線・丸・四角・矢印・マーカーが重なっていたら、生徒がペンで書き込んだもの。囲んだ所や矢印の先は生徒が聞きたい所、書いた文字や図は生徒の考えとして読み取る。画像を見て答える' }, image }
      : { result: { error: '生徒は画面を共有していません。見えないことを伝え、必要なら「画面を家トモに見せる」で共有してもらう' } };
  },
};
